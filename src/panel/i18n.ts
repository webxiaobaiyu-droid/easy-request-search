const LOCALE_KEY = 'easy-request-search:locale'

function initialLocale(): Locale {
  try {
    const stored = localStorage.getItem(LOCALE_KEY)
    if (stored === 'en' || stored === 'zh-CN') return stored
  } catch {
    // Storage may be unavailable in restricted DevTools contexts.
  }
  return 'zh-CN'
}

export const locale = ref<Locale>(initialLocale())

export function setLocale(next: Locale): void {
  locale.value = next
  try {
    localStorage.setItem(LOCALE_KEY, next)
  } catch {
    // Persistence is optional.
  }
}

export function toggleLocale(): void {
  setLocale(locale.value === 'zh-CN' ? 'en' : 'zh-CN')
}

/** Translate a key; `{n}` / `{x}` placeholders are replaced from params. */
export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const template = locale.value === 'en' ? en[key] : zhCN[key]
  const text = template ?? zhCN[key] ?? key
  if (!params) return text
  return Object.entries(params).reduce((acc, [name, value]) => acc.replaceAll(`{${name}}`, String(value)), text)
}
